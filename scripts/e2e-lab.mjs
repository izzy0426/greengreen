// 실험실 동작 확인 (개발용): node scripts/e2e-lab.mjs [http://localhost:4173]
import puppeteer from 'puppeteer-core'
const base = process.argv[2] ?? 'http://localhost:4173'
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const p = await b.newPage()
const errs = []
p.on('pageerror', (e) => errs.push(e.message))
p.on('console', (m) => m.type() === 'error' && errs.push(m.text()))
await p.setViewport({ width: 1440, height: 1036 })
const ok = (l, c) => console.log(`${c ? 'OK  ' : 'FAIL'} ${l}`)
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const meter = () => p.$eval('.meter', (e) => e.getAttribute('aria-valuetext'))

await p.goto(`${base}/lab`, { waitUntil: 'networkidle0' })
ok(`기본 미터 ${await meter()}`, (await meter()) === '+4.8%')
const sliders = await p.$$('.lever__slider')
ok(`레버 9개`, sliders.length === 9)
await sliders[7].focus()
await p.keyboard.press('ArrowUp')
await sliders[7].focus()
await p.keyboard.press('ArrowUp')
await sleep(900)
ok(`↑↑ 감축 3단계 → URL ${p.url().split('?')[1]}`, p.url().endsWith('lever=211112231'))
ok(`미터 ${await meter()}`, (await meter()) === '−0.4%')
const toast = await p.$eval('.lab-toast', (e) => e.textContent).catch(() => '')
ok(`토스트: ${toast}`, toast.includes('+4.8% → −0.4%'))
const pin = await p.$eval('.pin .pin__value', (e) => e.textContent)
ok(`발전 핀: ${pin}`, pin.includes('2.33조') && pin.includes('▼'))
await sleep(3200)
ok('토스트 3초 뒤 사라짐', (await p.$('.lab-toast')) === null)

await sliders[1].focus()
await p.keyboard.press('ArrowUp')
await sleep(300)
const m2 = await meter()
const badge = await p.$$eval('.lever', (els) => els[1].querySelector('.tag--assume') !== null)
ok(`총량 2단계(미정): 숫자 그대로 ${m2}, 가정 배지 ${badge}`, m2 === '−0.4%' && badge)

const href = await p.$eval('#header-actions a.btn--primary', (e) => e.getAttribute('href'))
ok(`결과 보기 링크 ${href}`, href === '/lab/result?lever=221112231')
await p.click('#header-actions button')
await sleep(300)
ok(`초기화 → ${p.url()}`, p.url().endsWith('/lab'))

await p.goto(`${base}/lab?lever=411112231`, { waitUntil: 'networkidle0' })
const price = await p.$eval('.price-box__value', (e) => e.textContent)
ok(`주소로 바로 진입 (매우 높은 가격 + 감축 3): ${price}, 미터 ${await meter()}`, price.startsWith('115,000') && (await meter()) === '−0.4%')
await p.goto(`${base}/lab?lever=999`, { waitUntil: 'networkidle0' })
ok(`잘못된 lever → 기본 ${await meter()}`, (await meter()) === '+4.8%')

await p.goto(`${base}/lab/result?lever=211112231`, { waitUntil: 'networkidle0' })
const kpis = await p.$$eval('.kpi-card__number', (els) => els.map((e) => e.textContent))
ok(`07 KPI ${kpis.join(' / ')}`, kpis.join('|') === '434.2|−0.4|9.9|337.0')
const back = await p.$eval('#header-actions a', (e) => e.getAttribute('href'))
ok(`레버로 돌아가기 ${back}`, back === '/lab?lever=211112231')
ok(`경로 제출하기 비활성`, await p.$eval('#header-actions button', (e) => e.disabled))
ok(`콘솔 오류 없음 ${errs.join(' | ')}`, errs.length === 0)
await b.close()
